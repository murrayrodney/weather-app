// Single generator/checker for security headers (Node built-ins only).
//   node scripts/headers.mjs generate [--update-announcer-hash]
//   node scripts/headers.mjs check
// Source of truth: web/security-headers.json. Outputs: the generated block in web/netlify.toml and ../ops/caddy/security-headers.caddy.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { findAnnouncer } from './announcer.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = join(root, 'security-headers.json');
const tomlPath = join(root, 'netlify.toml');
const caddyDir = join(root, '..', 'ops', 'caddy');
const caddyOutPath = join(caddyDir, 'security-headers.caddy');
const caddyfilePath = join(caddyDir, 'Caddyfile');
const BEGIN = '# BEGIN GENERATED HEADERS (scripts/headers.mjs generate; do not edit by hand)';
const END = '# END GENERATED HEADERS';

const readJson = () => JSON.parse(readFileSync(jsonPath, 'utf8'));

export function buildCsp(cfg, production) {
  const merged = new Map();
  for (const [k, v] of Object.entries(cfg.csp)) merged.set(k, [...v]);
  if (production) {
    for (const [k, v] of Object.entries(cfg.csp_production_additions)) merged.set(k, [...(merged.get(k) ?? []), ...v]);
  }
  return [...merged].map(([k, v]) => [k, ...v].join(' ')).join('; ');
}

const q = (s) => JSON.stringify(s);

export function netlifyBlock(cfg) {
  const lines = [BEGIN, '[[headers]]', '  for = "/*"', '  [headers.values]'];
  lines.push(`    Content-Security-Policy = ${q(buildCsp(cfg, true))}`);
  for (const [k, v] of Object.entries({ ...cfg.headers_all, ...cfg.headers_production_only })) lines.push(`    ${k} = ${q(v)}`);
  for (const [path, value] of Object.entries(cfg.cache_control)) {
    lines.push('', '[[headers]]', `  for = ${q(path)}`, '  [headers.values]', `    Cache-Control = ${q(value)}`);
  }
  lines.push(END);
  return lines.join('\n');
}

export function caddyFile(cfg) {
  const lines = [
    '# GENERATED by web/scripts/headers.mjs from web/security-headers.json. Do not edit by hand.',
    '# Local variant: no HSTS, no upgrade-insecure-requests, no Cache-Control (the Caddyfile sets that per matcher).',
    'header {',
    `\tContent-Security-Policy ${q(buildCsp(cfg, false))}`
  ];
  for (const [k, v] of Object.entries(cfg.headers_all)) lines.push(`\t${k} ${q(v)}`);
  lines.push('}', '');
  return lines.join('\n');
}

function spliceBlock(toml, block) {
  const a = toml.indexOf(BEGIN);
  const b = toml.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('netlify.toml is missing the GENERATED HEADERS markers');
  return toml.slice(0, a) + block + toml.slice(b + END.length);
}

function generate(update) {
  if (update) {
    const found = findAnnouncer(join(root, 'build'));
    if (!found) throw new Error('announcer style literal not found in build/ (run npm run build first)');
    const raw = readFileSync(jsonPath, 'utf8');
    const next = raw.replace(/'sha256-[A-Za-z0-9+/=]+'/, `'sha256-${found.hash}'`);
    writeFileSync(jsonPath, next);
    console.log(`announcer hash set to sha256-${found.hash}`);
  }
  const cfg = readJson();
  writeFileSync(tomlPath, spliceBlock(readFileSync(tomlPath, 'utf8'), netlifyBlock(cfg)));
  writeFileSync(caddyOutPath, caddyFile(cfg));
  console.log('wrote web/netlify.toml header block and ops/caddy/security-headers.caddy');
}

function check() {
  const cfg = readJson();
  const errors = [];
  const fail = (m) => errors.push(m);

  // 1. generated outputs match
  const toml = readFileSync(tomlPath, 'utf8');
  try {
    if (spliceBlock(toml, netlifyBlock(cfg)) !== toml) fail('netlify.toml header block differs from `headers.mjs generate`');
  } catch (e) {
    fail(e.message);
  }
  if (!existsSync(caddyOutPath)) fail('ops/caddy/security-headers.caddy is missing');
  else if (readFileSync(caddyOutPath, 'utf8') !== caddyFile(cfg)) fail('ops/caddy/security-headers.caddy differs from `headers.mjs generate`');

  // 2. Caddyfile contract (05 section 5.3)
  if (existsSync(caddyfilePath)) {
    const cf = readFileSync(caddyfilePath, 'utf8');
    const need = ['import /etc/caddy/security-headers.caddy', 'header -Server', '@immutable', '@mutable', 'rewrite @root /200.html', 'try_files {path} /200.html'];
    for (const t of need) if (!cf.includes(t)) fail(`Caddyfile is missing: ${t}`);
    const iApp = cf.indexOf('handle /_app/*');
    const iCatch = cf.search(/^\thandle \{/m);
    if (iApp < 0) fail('Caddyfile has no `handle /_app/*` block');
    else if (iCatch < 0 || iApp > iCatch) fail('Caddyfile: `handle /_app/*` must appear before the catch-all `handle {`');
    else if (cf.slice(iCatch).indexOf('try_files {path} /200.html') < 0) fail('Caddyfile: try_files must be inside the catch-all handler');
    for (const bad of ['Content-Security-Policy', 'X-Frame-Options', 'Strict-Transport-Security', 'Referrer-Policy', 'Permissions-Policy', 'Cross-Origin-', 'X-Content-Type-Options', 'X-Robots-Tag']) {
      if (cf.includes(bad)) fail(`Caddyfile defines a security header of its own: ${bad}`);
    }
  }

  // 3. redirect invariants + no wildcard CSP sources
  const iApi = toml.indexOf('from = "/api/*"');
  const iApp = toml.indexOf('from = "/_app/*"');
  const iAll = toml.indexOf('from = "/*"');
  if (iApi < 0 || iAll < 0 || iApi > iAll) fail('netlify.toml: the /api/* rule must appear before the /* rule');
  if (iApp < 0 || iApp > iAll) fail('netlify.toml: the /_app/* 404 rule must appear before the /* rule');
  if (!/^\s*#\s*signed = "NETLIFY_PROXY_SECRET"/m.test(toml) || /^\s*signed\s*=/m.test(toml)) {
    fail('netlify.toml: `signed = "NETLIFY_PROXY_SECRET"` must be present and commented out');
  }
  for (const [name, srcs] of Object.entries({ ...cfg.csp, ...cfg.csp_production_additions })) {
    for (const s of srcs) if (/(^|\/\/)\*/.test(s) || s === '*' || /^[a-z]+:$/.test(s)) fail(`CSP ${name} has a wildcard or scheme source: ${s}`);
  }
  const unsafe = Object.entries(cfg.csp).flatMap(([k, v]) => v.filter((s) => s.includes('unsafe-')).map((s) => `${k} ${s}`));
  if (unsafe.length !== 1 || unsafe[0] !== "style-src-attr 'unsafe-hashes'") fail(`the only unsafe-* token allowed is style-src-attr 'unsafe-hashes'; found: ${unsafe.join(', ')}`);

  // 4. production context
  if (process.env.CONTEXT === 'production') {
    const prodConnect = buildCsp(cfg, true).match(/connect-src ([^;]*)/)?.[1] ?? '';
    if (prodConnect.includes('<project-ref>') || JSON.stringify(cfg).includes('<project-ref>')) {
      fail('<project-ref> is still a placeholder in security-headers.json (fill it and run `npm run headers:generate`)');
    }
    let origin = '';
    try {
      origin = new URL(process.env.PUBLIC_SUPABASE_URL ?? '').origin;
    } catch {
      fail('PUBLIC_SUPABASE_URL is not a valid URL');
    }
    if (origin && !prodConnect.split(' ').includes(origin)) fail(`connect-src does not contain the origin of PUBLIC_SUPABASE_URL (${origin})`);
  }

  if (errors.length) {
    for (const e of errors) console.error(`headers:check FAIL: ${e}`);
    process.exit(1);
  }
  console.log('headers:check ok');
}

const [cmd, ...flags] = process.argv.slice(2);
if (cmd === 'generate') generate(flags.includes('--update-announcer-hash'));
else if (cmd === 'check') check();
else {
  console.error('usage: headers.mjs generate [--update-announcer-hash] | check');
  process.exit(2);
}
